"""Reproducible responsive derivatives; never overwrite original photographs.
Run with Pillow installed: python scripts/prepare-images.py
"""
from pathlib import Path
from PIL import Image, ImageOps
import hashlib
import json
import re
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'assets' / 'responsive'
DEST.mkdir(parents=True, exist_ok=True)
assets = {}
for path in sorted([*ROOT.glob('*.jpeg'), *(ROOT / 'assets/photos').glob('*.jpeg')]):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    with Image.open(path) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        width, height = image.size
        variants = []
        for target in sorted(set([min(width, n) for n in [320, 480, 736]])):
            resized = image.resize((target, round(height * target / width)), Image.Resampling.LANCZOS)
            filename = f'{digest}-{target}.webp'
            resized.save(DEST / filename, 'WEBP', quality=82, method=6)
            variants.append(f'./assets/responsive/{filename} {target}w')
        assets[path.relative_to(ROOT).as_posix()] = dict(width=width, height=height, srcset=', '.join(variants))
(ROOT / 'image-assets.js').write_text('/* Generated by scripts/prepare-images.py; originals preserved. */\nwindow.LockdImageAssets = Object.freeze(' + json.dumps(assets, separators=(',', ':')) + ');\n', encoding='utf-8')

# Intrinsic dimensions and candidates work even before JavaScript (or with it off).
for page in ROOT.glob('*.html'):
    text = page.read_text(encoding='utf-8')
    def update(match):
        tag = match[0]
        src = re.search(r'\bsrc="([^"]+)"', tag)
        asset = assets.get(unquote(src[1]).removeprefix('./')) if src else None
        if not asset:
            return tag
        for key in ['width', 'height', 'srcset', 'sizes', 'decoding', 'loading']:
            tag = re.sub(r'\s' + key + r'="[^"]*"', '', tag)
        sizes = '(max-width: 760px) 100vw, 60vw' if 'fetchpriority="high"' in tag else '(max-width: 600px) 100vw, (max-width: 1000px) 50vw, 33vw'
        attrs = f' width="{asset["width"]}" height="{asset["height"]}" srcset="{asset["srcset"]}" sizes="{sizes}" decoding="async"'
        if 'fetchpriority="high"' not in tag:
            attrs += ' loading="lazy"'
        return tag[:-1] + attrs + '>'
    text = re.sub(r'<img\b[^>]*>', update, text)
    page.write_text(text, encoding='utf-8', newline='\n')
print(f'Prepared {len(assets)} original references; {len(list(DEST.glob("*.webp")))} deduplicated responsive assets.')
